"""质检流水线的共享异常。

核心原则: 把结果分成三类, 后两类**绝不**混进第一类。

    1. 数据坏了       -> 产出 finding, 走各检测自己的规则表 (删帧 / 删 episode)
    2. 运行环境不对   -> 抛 PipelineEnvironmentError, 不产出任何 finding
    3. 数据格式不支持 -> 抛 UnsupportedDataError, 不产出任何 finding

第 2、3 类由各检测**不捕获**地向上抛, 强制调用方显式处理。命中它们的 episode 应记为
"检测失败", 而不是"已检查且干净", 更不能被判成"数据损坏"。

为什么必须这样 (真实踩过的坑): 旧版 corrupt 里 pyav 没装会走进"视频整路无法解码"分支,
于是**每一条 episode 都被判成损坏并建议删除** —— 一个环境问题足以删光整个数据集, 而且
报告上每条都写着"数据损坏", 事后翻不出真实原因。

同类风险存在于任何"猜个默认值继续跑"的降级:

  - 拿不到 PTS 就退化成顺序计数 -> 帧号不再对应原始时间轴, 下游按错误帧号删 parquet 行,
    删完长度依然对得上, 事后无法发现
  - 拿不到 fps 就当 30 -> 所有"秒"阈值静默失真 (10fps 的视频等于阈值收紧 3 倍)
  - 源像素格式不认识就强转 rgb24 -> 真灰度视频被伪装成彩色放行

这些降级的共同点是: **结论看上去正常, 但已经不可信, 而且"不可信"这件事本身也丢失了。**
宁可停下来看一眼。
"""


class CheckError(Exception):
    """检测无法完成。

    这不是一条检测结果 —— 它表示我们**没能对这条 episode 给出可信结论**。
    调用方必须单独记为"检测失败", 不能计入"已检查且干净", 也不能当成"数据损坏"。
    """


class PipelineEnvironmentError(CheckError):
    """运行环境问题: 依赖缺失 / 解码器不可用。与被检数据无关, 修环境后重跑即可。

    跑全量时这类异常的数量应该是 0。不是 0 就说明环境有问题, 该批结果全部作废重跑。
    """


class UnsupportedDataError(CheckError):
    """数据格式超出本检测的支持范围, 无法给出可信结论。

    典型场景: 拿不到 PTS / fps、源像素格式不在白名单、parquet 里认不出动作列、
    检测所需的输入没有提供。

    如果这类异常集中出现在某一批数据上, 先看清楚那批数据到底是什么格式, 再决定是放宽
    支持范围还是把它剔除 —— **不要为了让流程跑通而把报错改回降级**。
    """
